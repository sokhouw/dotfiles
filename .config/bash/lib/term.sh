dfg:term:h2d() {
    printf '%d' "$((16#${1}))"
}

dfg:term:esc() {
    case "${2}" in
        "#"*)
            printf '\033[%s;2;%s;%s;%sm' "${1}" "$(dfg:term:h2d ${2:1:2})" "$(dfg:term:h2d ${2:3:2})" "$(dfg:term:h2d ${2:5:2})"
            ;;
        *)
            printf '\033[%s;5;%sm' "${1}" "${2}"
            ;;
    esac
}

dfg:term:fg() {
    [ -z "${1}" ] || dfg:term:esc 38 "${1}"
}

dfg:term:bg() {
    [ -z "${1}" ] || dfg:term:esc 48 "${1}"
}

dfg:term:reset() {
    printf '\033[0m'
}
